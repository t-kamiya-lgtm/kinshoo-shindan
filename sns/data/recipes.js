export const getRecipe = (key) => RECIPES.find((r) => r.key === key) || null;

/**
 * 原稿のレシピを、表示に使える形に整える。
 *   ・手順の {boil} を商品のゆで時間（3〜5）に差し替える
 *   ・調理時間を、ゆで時間の上限で換算する
 * 画像・キャプションはどちらもこの結果を使うので、両者がずれることがない。
 */
export function resolveRecipe(recipe, product) {
  const [, boilMax] = product.boilRange;
  const boilText = product.boilMin;              // 例 '3〜5'
  const minutes = recipe.minutesBase - recipe.boilBase + boilMax;
  return {
    ...recipe,
    minutes,
    boilText,
    steps: recipe.steps.map((s) => s.replace(/\{boil\}/g, boilText))
  };
}
