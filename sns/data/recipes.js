/** 比較用にファイル名をならす（拡張子・記号・全角半角の差を吸収） */
function normalizeForMatch(name) {
  return String(name)
    .replace(/^.*[\\/]/, '')
    .replace(/\.[a-z0-9]+$/i, '')
    .replace(/[\s_\-.（）()［］\[\]]/g, '')
    .toLowerCase();
}

